package com.example.quant.agent.execution;

import java.math.BigDecimal;
import java.time.Instant;

public record AutoTradeRecordView(
        Long id,
        String status,
        String userName,
        String triggerType,
        String instId,
        String tradePlanId,
        String pendingOrderId,
        String okxOrderId,
        String action,
        String posSide,
        Integer leverage,
        BigDecimal marginAmount,
        BigDecimal entryPrice,
        int candidateCount,
        Integer candidateScore,
        String trendDirection,
        BigDecimal lastPrice,
        BigDecimal riskRewardRatio,
        BigDecimal spreadBps,
        BigDecimal bidDepthUsdt,
        BigDecimal askDepthUsdt,
        String marketRiskLevel,
        String message,
        String scanId,
        String scanCoverage,
        BigDecimal finalRankScore,
        String signalType,
        String scanAction,
        String riskMode,
        String stage,
        String reasonCode,
        String reasonMessage,
        Boolean fallbackAllowed,
        String decisionSource,
        BigDecimal aiConfidence,
        String aiDirection,
        String aiEntryMode,
        String selectionReason,
        String aiObservationId,
        String aiRejectionCode,
        Instant createdAt,
        Instant updatedAt
) {
    public static AutoTradeRecordView from(AutoTradeRecordEntity entity) {
        return new AutoTradeRecordView(
                entity.getId(),
                entity.getStatus(),
                entity.getUserName(),
                entity.getTriggerType(),
                entity.getInstId(),
                entity.getTradePlanId(),
                entity.getPendingOrderId(),
                entity.getOkxOrderId(),
                "SKIPPED".equals(entity.getStatus()) ? null : entity.getAction(),
                "SKIPPED".equals(entity.getStatus()) ? null : entity.getPosSide(),
                entity.getLeverage(),
                entity.getMarginAmount(),
                entity.getEntryPrice(),
                entity.getCandidateCount(),
                entity.getCandidateScore(),
                entity.getTrendDirection(),
                entity.getLastPrice(),
                entity.getRiskRewardRatio(),
                entity.getSpreadBps(),
                entity.getBidDepthUsdt(),
                entity.getAskDepthUsdt(),
                entity.getMarketRiskLevel(),
                entity.getMessage(),
                entity.getScanId(),
                entity.getScanCoverage(),
                entity.getFinalRankScore(),
                entity.getSignalType(),
                entity.getScanAction(),
                entity.getRiskMode(),
                entity.resolveStage(entity.getStage()),
                entity.getReasonCode(),
                entity.getReasonMessage(),
                entity.getFallbackAllowed(),
                entity.getDecisionSource(),
                entity.getAiConfidence(),
                entity.getAiDirection(),
                entity.getAiEntryMode(),
                entity.getSelectionReason(),
                entity.getAiObservationId(),
                entity.getAiRejectionCode(),
                entity.getCreatedAt(),
                entity.getUpdatedAt()
        );
    }
}
